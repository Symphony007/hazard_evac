"""Evacuation performance metrics per agent and per experiment run.

Defines the canonical metrics schema matching PROJECT_CONTEXT.md.
"""

from __future__ import annotations

from typing import TYPE_CHECKING, Sequence

import numpy as np
import pandas as pd

if TYPE_CHECKING:
    from src.sim.single_agent import AgentResult


def per_agent_frame(
    results: Sequence[AgentResult],
    baseline_len: dict[int | str, float],
) -> pd.DataFrame:
    """Convert a sequence of AgentResult instances into a standardized DataFrame.

    Parameters
    ----------
    results : Sequence[AgentResult]
        Outcomes for individual evacuees.
    baseline_len : dict[int | str, float]
        No-hazard shortest road length from each node to its nearest exit.

    Returns
    -------
    pd.DataFrame
        DataFrame with one row per agent and scalar columns:
        - agent_id, router_name, origin, safe, trapped_reason
        - depart_time_s, finish_time_s, evac_time_s
        - path_length_m, baseline_length_m, path_overhead
        - n_path_nodes, n_replans, compute_ms, trap_time_s
        - max_congestion (placeholder for Task 5, always NaN here)
    """
    rows = []
    for r in results:
        origin = r.path_nodes[0] if r.path_nodes else None
        base_dist = baseline_len.get(origin, np.nan) if origin is not None else np.nan

        if r.safe and np.isfinite(base_dist) and base_dist > 0.0:
            overhead = float(r.path_length_m / base_dist)
        else:
            overhead = float(np.nan)

        rows.append(
            {
                "agent_id": r.agent_id,
                "router_name": r.router_name,
                "origin": origin,
                "safe": bool(r.safe),
                "trapped_reason": r.trapped_reason if r.trapped_reason is not None else "none",
                "depart_time_s": float(r.depart_time_s),
                "finish_time_s": float(r.finish_time_s) if r.finish_time_s is not None else float(np.nan),
                "evac_time_s": float(r.evac_time_s) if r.evac_time_s is not None else float(np.nan),
                "path_length_m": float(r.path_length_m),
                "baseline_length_m": float(base_dist),
                "path_overhead": overhead,
                "n_path_nodes": len(r.path_nodes),
                "n_replans": int(r.n_replans),
                "compute_ms": float(r.compute_ms),
                "trap_time_s": float(r.trap_time_s) if r.trap_time_s is not None else float(np.nan),
                "queue_delay_s": float(getattr(r, "queue_delay_s", 0.0)),
                "n_fallback_plans": int(getattr(r, "n_fallback_plans", 0)),
                "max_congestion": float(np.nan),  # Placeholder schema for Task 5
            }
        )

    return pd.DataFrame(rows)


def run_metrics(
    df: pd.DataFrame,
    edge_stats: pd.DataFrame | None = None,
    ceiling_pct: float | None = None,
) -> dict[str, float | int]:
    """Compute aggregate evaluation metrics from a per-agent DataFrame.

    Fixed Metric Names
    ------------------
    - pct_safe : float
        Percentage of evacuees that reach a safe exit (0 to 100).
    - ceiling_pct : float
        Single-agent time_dependent oracle ceiling (% of agents savable with unlimited capacity).
    - congestion_loss_pct : float
        Congestion loss percentage (ceiling_pct - pct_safe).
    - mean_evac_min : float
        Mean evacuation duration in minutes for safe evacuees (NaN if 0 safe).
    - p90_evac_min : float
        90th percentile evacuation duration in minutes for safe evacuees (NaN if 0 safe).
    - last_evac_min : float
        Time until last safe evacuee reaches an exit in minutes (NaN if 0 safe).
    - mean_path_overhead : float
        Mean ratio of actual path length to static shortest path for safe evacuees (NaN if 0 safe).
    - mean_compute_ms : float
        Mean CPU computation time per replan/agent in milliseconds.
    - n_trapped_no_route : int
        Number of evacuees who could find no feasible initial or replanned path.
    - n_trapped_en_route : int
        Number of evacuees caught by flood waters while traversing an edge.
    - n_agents : int
        Total number of evacuees simulated in this run.
    - max_congestion : float
        Maximum edge occupancy ratio (peak_occupancy / storage_capacity) across all edges.
    - n_edges_over_storage : int | float
        Number of edges where peak occupancy exceeded storage capacity.
    - mean_queue_delay_s : float
        Mean queuing delay across all simulated agents in seconds.
    - p90_queue_delay_s : float
        90th percentile queuing delay across all agents in seconds.
    - max_queue_wait_s : float
        Maximum single-edge queuing wait observed in seconds.

    Parameters
    ----------
    df : pd.DataFrame
        Per-agent DataFrame generated by :func:`per_agent_frame`.
    edge_stats : pd.DataFrame, optional
        Per-edge statistics DataFrame generated by multi-agent simulation.

    Returns
    -------
    dict[str, float | int]
        Aggregated run metrics.
    """
    n_agents = len(df)
    if n_agents == 0:
        return {
            "pct_safe": float(np.nan),
            "ceiling_pct": float(np.nan),
            "congestion_loss_pct": float(np.nan),
            "mean_evac_min": float(np.nan),
            "p90_evac_min": float(np.nan),
            "last_evac_min": float(np.nan),
            "mean_path_overhead": float(np.nan),
            "mean_compute_ms": float(np.nan),
            "n_trapped_no_route": 0,
            "n_trapped_en_route": 0,
            "n_agents": 0,
            "max_congestion": float(np.nan),
            "n_edges_over_storage": float(np.nan),
            "mean_queue_delay_s": float(np.nan),
            "p90_queue_delay_s": float(np.nan),
            "max_queue_wait_s": float(np.nan),
        }

    safe_df = df[df["safe"]]
    n_safe = len(safe_df)
    pct_safe = float(100.0 * n_safe / n_agents)

    if n_safe > 0:
        evac_times_min = safe_df["evac_time_s"].dropna() / 60.0
        mean_evac = float(evac_times_min.mean()) if not evac_times_min.empty else float(np.nan)
        p90_evac = float(np.percentile(evac_times_min, 90)) if not evac_times_min.empty else float(np.nan)
        last_evac = float(evac_times_min.max()) if not evac_times_min.empty else float(np.nan)

        overheads = safe_df["path_overhead"].dropna()
        mean_overhead = float(overheads.mean()) if not overheads.empty else float(np.nan)
    else:
        mean_evac = float(np.nan)
        p90_evac = float(np.nan)
        last_evac = float(np.nan)
        mean_overhead = float(np.nan)

    mean_compute = float(df["compute_ms"].mean()) if not df["compute_ms"].empty else float(np.nan)
    n_no_route = int((df["trapped_reason"] == "no_route").sum())
    n_en_route = int((df["trapped_reason"] == "edge_closed_en_route").sum())

    # Task 5 Congestion Metrics
    if edge_stats is not None and not edge_stats.empty:
        caps = edge_stats["storage_capacity"].clip(lower=1)
        ratios = edge_stats["peak_occupancy"] / caps
        max_congestion = float(ratios.max())
        n_edges_over_storage = int((edge_stats["peak_occupancy"] > edge_stats["storage_capacity"]).sum())
        max_queue_wait_s = float(edge_stats["max_queue_wait_s"].max()) if "max_queue_wait_s" in edge_stats else float(np.nan)
        q_delays = df["queue_delay_s"].dropna() if "queue_delay_s" in df else pd.Series(dtype=float)
        mean_queue_delay_s = float(q_delays.mean()) if not q_delays.empty else 0.0
        p90_queue_delay_s = float(np.percentile(q_delays, 90)) if not q_delays.empty else 0.0
    else:
        max_congestion = float(np.nan)
        n_edges_over_storage = float(np.nan)
        max_queue_wait_s = float(np.nan)
        mean_queue_delay_s = float(np.nan)
        p90_queue_delay_s = float(np.nan)

    ceiling_val = float(ceiling_pct) if ceiling_pct is not None else float(np.nan)
    loss_val = float(ceiling_pct - pct_safe) if ceiling_pct is not None else float(np.nan)
    mean_fallback = float(df["n_fallback_plans"].mean()) if "n_fallback_plans" in df and not df.empty else 0.0

    return {
        "pct_safe": pct_safe,
        "ceiling_pct": ceiling_val,
        "congestion_loss_pct": loss_val,
        "mean_evac_min": mean_evac,
        "p90_evac_min": p90_evac,
        "last_evac_min": last_evac,
        "mean_path_overhead": mean_overhead,
        "mean_compute_ms": mean_compute,
        "n_trapped_no_route": n_no_route,
        "n_trapped_en_route": n_en_route,
        "n_fallback_plans": mean_fallback,
        "n_agents": n_agents,
        "max_congestion": max_congestion,
        "n_edges_over_storage": n_edges_over_storage,
        "mean_queue_delay_s": mean_queue_delay_s,
        "p90_queue_delay_s": p90_queue_delay_s,
        "max_queue_wait_s": max_queue_wait_s,
    }

